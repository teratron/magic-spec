#!/usr/bin/env node
'use strict';

// Help and unknown options are answered before this script reads or writes anything.
require('./cli-guard').guardCli('validate-hardlinks', module);

const fs = require('fs');
const path = require('path');

// ═══════════════════════════════════════════════════════════════════════════
// LINK VALIDATION (Agent Rule Cards + Skill Links)
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Verifies the link inventory of l2-agent-surface.md §4:
 *
 *   1. Per-vendor agent rule files (CLAUDE.md, GEMINI.md, QWEN.md, CODEX.md)
 *      share the same inode as the AGENTS.md anchor (hardlinks).
 *   2. Directory links: each entry of LINKS is a symbolic link or junction
 *      whose real path is its target, so that editing a file through the host
 *      folder edits the one real file (l2-skill-layout.md §5.6).
 *
 * The always-on rule's installed copy and the command entries are generated by
 * `init --host`, not linked: their staleness is reported by init, not here.
 *
 * Why: the project deliberately uses links instead of duplicated files. If an
 * editor or a careless `cp` replaces one of them, agents will diverge. This
 * script doesn't auto-repair — it surfaces the drift so the user can run
 * `/magicspec-dev:init` (the canonical link-rebuild path).
 *
 * Junction safety: create a link only after its path is out of the git index
 * (`git rm --cached` on the specific files first, never on a path reached
 * through a junction) — see the repository guide, section 6.
 *
 * Exit codes:
 *   0 — all good, or only soft warnings (missing optional siblings)
 *   1 — drift detected (different inodes, a copy where a link belongs, etc.)
 *
 * Flags:
 *   --strict   Treat any missing sibling or link as a hard error
 */

const { ENGINE_DIR } = require('./engine-path');
const ENGINE_POSIX = ENGINE_DIR.split(require('path').sep).join('/');

const projectRoot = process.cwd();
const ANCHOR = 'AGENTS.md';
const SIBLINGS = ['CLAUDE.md', 'GEMINI.md', 'QWEN.md', 'CODEX.md'];
// Directory links of the repository: where the host looks, and the real folder it must reach.
const LINKS = [
    { link: path.join('.agents', 'skills', 'magicspec'), target: ENGINE_DIR },
    {
        link: path.join('.agents', 'skills', 'magicspec-dev'),
        target: path.join('skills', 'magicspec-dev'),
    },
];

const args = process.argv.slice(2);
const strict = args.includes('--strict');

function statSafe(p) {
    try {
        // BigInt: Windows file ids exceed 2^53, and two different ids must not round to one number.
        return fs.statSync(p, { bigint: true });
    } catch {
        return null;
    }
}

function fingerprint(stat) {
    // On Windows, `ino` is derived from the file's file index (BY_HANDLE_FILE_INFORMATION),
    // read as a BigInt so it is exact. Hardlinks share inode + dev.
    return `${stat.dev}:${stat.ino}`;
}

/**
 * Tallies per-item classify results (each `'missing'`/`'drift'`/`'linked'`,
 * `null` silently ignored) into outcome counts — shared by both link groups
 * below, which otherwise differ only in how each item is classified.
 *
 * @param {(string|null)[]} results
 * @returns {{ missing: number, drift: number, linked: number }}
 */
function tallyLinkResults(results) {
    return {
        missing: results.filter((r) => r === 'missing').length,
        drift: results.filter((r) => r === 'drift').length,
        linked: results.filter((r) => r === 'linked').length,
    };
}

// ───────────────────────────────────────────────────────────────────────────
// Group 1 — AGENTS.md siblings
// ───────────────────────────────────────────────────────────────────────────

/**
 * Compares one sibling file's inode against the AGENTS.md anchor's and logs
 * the outcome.
 *
 * @param {string} sib - Sibling filename (e.g. `CLAUDE.md`).
 * @param {string} anchorFp - The anchor's `fingerprint()` value.
 * @returns {'missing'|'drift'|'linked'}
 */
function classifySibling(sib, anchorFp) {
    const sibPath = path.join(projectRoot, sib);
    const sibStat = statSafe(sibPath);

    if (!sibStat) {
        const tag = strict ? '❌' : '⚠️';
        console.log(`   ${tag} Missing: ${sib}`);
        return 'missing';
    }

    const sibFp = fingerprint(sibStat);
    if (sibFp !== anchorFp) {
        console.error(`   ❌ Drift: ${sib} has different inode (${sibFp} ≠ ${anchorFp}).`);
        return 'drift';
    }
    console.log(`   ✅ ${sib} → linked`);
    return 'linked';
}

function validateAgentsLinks() {
    console.log('🔍 Validating hardlinks for agent rule cards...');

    const anchorPath = path.join(projectRoot, ANCHOR);
    const anchorStat = statSafe(anchorPath);
    if (!anchorStat) {
        console.error(`   ❌ Anchor missing: ${ANCHOR}. Run /magicspec-dev:init.`);
        return { drift: 1, missing: 0, fatal: true };
    }

    const anchorFp = fingerprint(anchorStat);
    console.log(`   📎 Anchor: ${ANCHOR} (inode=${anchorFp}, nlink=${anchorStat.nlink})`);

    const { missing, drift, linked } = tallyLinkResults(
        SIBLINGS.map((sib) => classifySibling(sib, anchorFp)),
    );

    const summary =
        missing > 0
            ? `${linked}/${SIBLINGS.length} linked, ${missing} missing`
            : `all ${SIBLINGS.length} siblings linked to ${ANCHOR}`;
    console.log(`   ↳ ${summary}.`);

    return { drift, missing, fatal: false };
}

// ───────────────────────────────────────────────────────────────────────────
// Directory links (host skills folder → skill folder)
// ───────────────────────────────────────────────────────────────────────────

/**
 * @param {string} p - Path to inspect.
 * @returns {boolean} True for a symbolic link or a junction, without following it.
 */
function isLink(p) {
    try {
        return fs.lstatSync(p).isSymbolicLink();
    } catch {
        return false;
    }
}

/**
 * @param {string} p - Path to resolve.
 * @returns {string|null} Its real path, or null when it does not exist.
 */
function realOrNull(p) {
    try {
        return fs.realpathSync.native(p);
    } catch {
        return null;
    }
}

/**
 * Checks one directory link: it exists, it is a link (not a copy), and it leads to the target.
 *
 * @param {{link: string, target: string}} entry - One row of LINKS, both project-relative.
 * @returns {'missing'|'drift'|'linked'}
 */
function classifyLink(entry) {
    const linkPath = path.join(projectRoot, entry.link);
    const targetReal = realOrNull(path.join(projectRoot, entry.target));
    if (!fs.existsSync(linkPath) && !isLink(linkPath)) {
        const tag = strict ? '❌' : '⚠️';
        console.log(
            `   ${tag} Missing: ${entry.link}. Run: node ${ENGINE_POSIX}/scripts/executor.js init --host=codex`,
        );
        return 'missing';
    }
    if (!isLink(linkPath)) {
        console.error(
            `   ❌ Drift: ${entry.link} is a copy, not a link to ${entry.target}. Remove it, then run /magicspec-dev:init.`,
        );
        return 'drift';
    }
    if (targetReal === null || realOrNull(linkPath) !== targetReal) {
        console.error(`   ❌ Drift: ${entry.link} does not lead to ${entry.target}.`);
        return 'drift';
    }
    console.log(`   ✅ ${entry.link} → ${entry.target}`);
    return 'linked';
}

function validateDirectoryLinks() {
    console.log('\n🔍 Validating directory links (host skills folder → skill folder)...');
    const { missing, drift, linked } = tallyLinkResults(LINKS.map(classifyLink));
    console.log(
        `   ↳ ${linked}/${LINKS.length} linked${missing > 0 ? `, ${missing} missing` : ''}.`,
    );
    return { drift, missing, fatal: false };
}

// ───────────────────────────────────────────────────────────────────────────
// Aggregation
// ───────────────────────────────────────────────────────────────────────────

function main() {
    const agents = validateAgentsLinks();
    if (agents.fatal) process.exit(1);

    const directories = validateDirectoryLinks();

    const totalDrift = agents.drift + directories.drift;
    const totalMissing = agents.missing + directories.missing;

    if (totalDrift > 0) {
        console.error(
            `\n❌ Link validation failed: ${totalDrift} drifted file(s) or link(s). Run /magicspec-dev:init to rebuild.`,
        );
        process.exit(1);
    }

    if (strict && totalMissing > 0) {
        console.error(
            `\n❌ Link validation failed (strict): ${totalMissing} sibling(s) or link(s) missing.`,
        );
        process.exit(1);
    }

    if (totalMissing > 0) {
        console.log(`\n✅ Hardlink validation: passed with ${totalMissing} non-strict warning(s).`);
    } else {
        console.log(`\n✅ Hardlink validation: all groups linked correctly.`);
    }
}

module.exports = { validateAgentsLinks, validateDirectoryLinks, main };

if (require.main === module) {
    try {
        main();
    } catch (e) {
        console.error(`❌ Hardlink validation crashed: ${e.message}`);
        process.exit(1);
    }
}
