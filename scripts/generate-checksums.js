#!/usr/bin/env node
'use strict';

// Help and unknown options are answered before this script reads or writes anything.
require('./cli-guard').guardCli('generate-checksums', module);

const fs = require('fs');
const path = require('path');
const { ENGINE_DIR, enginePath } = require('./engine-path');
const {
    hashFileSafe,
    getAllFiles,
    normalizePath,
    writeFileSafe,
    VOLATILE_STATE_FILES,
    loadGitignore,
    parseFlags,
    BUILD_NOISE_DIRS,
} = require(enginePath('scripts', 'utils'));

// ═══════════════════════════════════════════════════════════════════════════
// CHECKSUM GENERATOR (Kernel Integrity)
// ═══════════════════════════════════════════════════════════════════════════
//
// Developer-side tool: builds the engine folder's .checksums by hashing the whole folder.
// The release archive ships .checksums pre-generated; end users only VERIFY
// it via `update-engine-meta --check` (pre-commit hook). Users never need
// to (and should not) regenerate the manifest — drift is resolved by
// restoring the engine folder from origin, not by overwriting checksums.

const PROJECT_ROOT = path.join(__dirname, '..');

// The folder to build the manifest for: `--dir <path>` (relative to the repository root or
// absolute), the repository's engine folder when absent.
const { values: flagValues, errors: flagErrors } = parseFlags(process.argv.slice(2), {
    valueFlags: ['--dir'],
});
if (flagErrors.length > 0) {
    console.error(`HALT: ${flagErrors[0]}`);
    process.exit(1);
}
const MAGIC_DIR = path.resolve(PROJECT_ROOT, flagValues['--dir'] || ENGINE_DIR);
const CHECKSUMS_FILE = '.checksums';
const CHECKSUMS_PATH = path.join(MAGIC_DIR, CHECKSUMS_FILE);

// history/ is an autogenerated audit log — its hashes change on every bump
// and would pollute .checksums + cause spurious ENGINE_INTEGRITY warnings.
// Unioned with the shared build-noise floor (Invariant 7 parity, see below).
const IGNORE_DIRS = ['history', ...BUILD_NOISE_DIRS];

// Volatile per-project caches (see utils.VOLATILE_STATE_FILES). These live
// inside the engine folder but are written by sync sub-scripts during normal user
// activity, so they must NOT be part of the integrity manifest.
const IGNORE_REL_FILES = VOLATILE_STATE_FILES;

// Invariant 7 parity (l2-engine-automation.md §Scan Hygiene): a manifest
// entry for a path the project itself disowns via .gitignore can never be
// satisfied by a real release archive (built from a fresh CI checkout — see
// .github/workflows/release.yml). Without this, a third-party tool cache
// created inside the engine folder by mistake on a developer machine (e.g. `.fallow/`,
// itself `.gitignore`d at the project root) gets baked into the shipped
// manifest, and every consumer install fails `update-engine-meta --check`
// on its very first commit with no self-heal path.
const isGitignored = loadGitignore(PROJECT_ROOT);

// ───────────────────────────────────────────────────────────────────────────
// Core Logic
// ───────────────────────────────────────────────────────────────────────────

function run() {
    console.log(
        `Generating checksums for ${normalizePath(path.relative(PROJECT_ROOT, MAGIC_DIR))}/ content...`,
    );

    // Integrity scope: the whole engine folder. Projections outside it (the rule
    // copy, the command entries) are generated from it and checked by init.
    const scanZones = [{ dir: MAGIC_DIR, relBase: MAGIC_DIR }];

    const checksums = {};

    const entries = [];
    scanZones.forEach((zone) => {
        if (!fs.existsSync(zone.dir)) return;

        getAllFiles(zone.dir, IGNORE_DIRS).forEach((fullPath) => {
            const rel = normalizePath(path.relative(zone.relBase, fullPath));
            if (rel === CHECKSUMS_FILE) return;
            if (IGNORE_REL_FILES.has(rel)) return;
            if (isGitignored(normalizePath(path.relative(PROJECT_ROOT, fullPath)))) return;
            entries.push({ rel, fullPath });
        });
    });

    // Sort entries by relative path for reproducibility
    entries
        .sort((a, b) => a.rel.localeCompare(b.rel))
        .forEach((entry) => {
            checksums[entry.rel] = hashFileSafe(entry.fullPath);
        });

    // Write to .checksums
    const output = JSON.stringify(checksums, null, 2);
    if (writeFileSafe(CHECKSUMS_PATH, output + '\n')) {
        console.log(`Successfully updated ${CHECKSUMS_PATH}`);
    }
    console.log(`Files processed: ${Object.keys(checksums).length}`);
}

run();
